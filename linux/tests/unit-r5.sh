echo "== r5: audit rules only for paths that exist"
R="$T/root5"; mkdir -p "$R/etc/ssh" "$R/etc/pam.d" "$R/usr/bin"
: > "$R/etc/passwd"; : > "$R/etc/shadow"; : > "$R/etc/ssh/sshd_config"; : > "$R/usr/bin/sudo"
rules="$(logging_audit_rules "$R")"
yes_ "passwd watched"           grep -qx -- '-w /etc/passwd -p wa -k identity' <<< "$rules"
yes_ "sshd_config watched"      grep -qx -- '-w /etc/ssh/sshd_config -p wa -k auth_config' <<< "$rules"
yes_ "sudo exec watched"        grep -qx -- '-w /usr/bin/sudo -p x -k privileged' <<< "$rules"
no_  "missing gshadow skipped"  grep -q 'gshadow' <<< "$rules"
eq   "rules are stable (same input, same file)" "$(logging_audit_rules "$R" | md5sum)" "$(echo "$rules" | md5sum)"

echo "== r5: core dump limits"
lf="$T/limits.conf"
printf '#<domain> <type> <item> <value>\n#*  soft  core  0\n@student hard core unlimited\nbob - core 100\n* soft nproc 50\n# End of file\n' > "$lf"
eq   "two lines raise the core limit"   "$(core_limit_lines "$lf" | wc -l | tr -d ' ')" "2"
no_  "not ok before the fix"            core_limits_ok "$lf" "$T/none.d"
core_limits_fix "$lf"
eq   "no raising line left"             "$(core_limit_lines "$lf" | wc -l | tr -d ' ')" "0"
yes_ "* hard core 0 added"              grep -qE '^\*[[:space:]]+hard[[:space:]]+core[[:space:]]+0' "$lf"
eq   "added above '# End of file'"      "$(tail -1 "$lf")" "# End of file"
yes_ "nproc line untouched"             grep -qx '\* soft nproc 50' "$lf"
yes_ "ok after the fix"                 core_limits_ok "$lf" "$T/none.d"
core_limits_fix "$lf"
eq   "second fix adds nothing"          "$(grep -cE '^\*[[:space:]]+hard[[:space:]]+core' "$lf")" "1"

