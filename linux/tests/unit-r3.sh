echo "== r3: sudoers 'Defaults !authenticate' (sudo with no password at all)"
s="$T/sudoers-README"
printf '#\n# This file MUST be edited with visudo\n#\nDefaults !authenticate\n# Defaults !authenticate (comment)\nDefaults\tenv_reset\n' > "$s"
eq   "live !authenticate line found"  "$(sudo_noauth_lines "$s" | wc -l | tr -d ' ')" "1"
sudo_comment_noauth "$s"
eq   "no live !authenticate left"     "$(sudo_noauth_lines "$s" | wc -l | tr -d ' ')" "0"
yes_ "env_reset untouched"            grep -qx "$(printf 'Defaults\tenv_reset')" "$s"
yes_ "line kept as a cpkit comment"   grep -q '^# cpkit disabled: Defaults !authenticate' "$s"

echo "== r3: Debian system accounts that must not have a login shell"
p="$T/passwd-sys"
printf 'root:x:0:0:root:/root:/bin/bash\nsys:x:3:3:sys:/dev:/bin/sh\nsync:x:4:65534:sync:/bin:/bin/sync\nwww-data:x:33:33::/var/www:/usr/sbin/nologin\ngames:x:5:60::/usr/games:/bin/bash\npostgres:x:113:120::/var/lib/postgresql:/bin/bash\njoy:x:1000:1000::/home/joy:/bin/bash\n' > "$p"
eq "sys + games flagged (root, sync, postgres, humans left alone)" "$(sys_shell_fix_list "$p" | xargs)" "sys games"

echo "== r3: lightdm accepts X connections over TCP"
l="$T/lightdm.conf"
printf '[Seat:*]\nxserver-allow-tcp = True\nautologin-user = joy\n' > "$l"
yes_ "xserver-allow-tcp True detected"  lightdm_tcp_on "$l"
printf '[Seat:*]\n#xserver-allow-tcp=true\nxserver-allow-tcp=false\n' > "$l"
no_  "false / commented ignored"        lightdm_tcp_on "$l"

echo "== r3: apps - apache security.conf"
a="$T/security.conf"
printf 'ServerTokens OS\nServerSignature On\nTraceEnable On\n#ServerTokens Full\n' > "$a"
eq "three apache keys to change" "$(apps_apache_plan "$a" | xargs)" "ServerTokens=Prod ServerSignature=Off TraceEnable=Off"
printf 'ServerTokens Prod\nServerSignature Off\nTraceEnable Off\n' > "$a"
eq "compliant security.conf -> nothing" "$(apps_apache_plan "$a")" ""
d="$T/apache2.conf"
printf '<Directory /var/www/>\n\tOptions Indexes FollowSymLinks\n\tAllowOverride None\n</Directory>\n<Directory /srv/>\n#\tOptions Indexes FollowSymLinks\n</Directory>\n' > "$d"
yes_ "directory listing (Options Indexes) found" apps_apache_indexes_on "$d"
apps_apache_noindexes "$d"
no_  "Indexes removed"                  apps_apache_indexes_on "$d"
yes_ "FollowSymLinks kept"              grep -qE '^[[:space:]]*Options FollowSymLinks$' "$d"

echo "== r3: apps - php.ini"
i="$T/php.ini"
printf 'expose_php = On\nsession.cookie_httponly =\nallow_url_include = Off\n' > "$i"
eq "php keys to change" "$(apps_php_plan "$i" | xargs)" "expose_php=Off session.cookie_httponly=1"

echo "== r3: apps - roundcube installer + dovecot ssl"
r="$T/config.inc.php"
printf "<?php\n\$config['imap_host'] = 'localhost:143';\n\$config['enable_installer'] = true;\n" > "$r"
yes_ "roundcube installer enabled detected" apps_roundcube_installer_on "$r"
apps_roundcube_installer_off "$r"
no_  "installer disabled after fix"         apps_roundcube_installer_on "$r"
yes_ "imap_host untouched"                  grep -q "imap_host'] = 'localhost:143'" "$r"
c="$T/10-ssl.conf"
printf '##\n## SSL settings\n##\nssl = no\nssl_cert = </etc/dovecot/private/dovecot.pem\n' > "$c"
eq "dovecot ssl value read" "$(cp_conf_get "$c" ssl)" "no"

echo "== r3: reverse-shell content (quarantine candidates)"
printf '#!/usr/bin/perl -w\n# perl-reverse-shell - A Reverse Shell implementation in PERL\nuse Socket;\n' > "$T/pearl"
printf '#!/bin/sh\nrun-parts /etc/cron.daily\n' > "$T/okjob"
yes_ "perl reverse shell recognised" revshell_suspect "$T/pearl"
no_  "ordinary script not flagged"   revshell_suspect "$T/okjob"
eq   "cron line -> command path"     "$(echo '*  *    * * *   root    pearl' | cron_line_cmd)" "pearl"
eq   "cron line with args"           "$(printf '17 *\t* * *\troot    /usr/local/bin/x --y' | cron_line_cmd)" "/usr/local/bin/x"
